export function getGameRank(hp, trust) {
  const score = hp + trust;
  if (score >= 180) {
    return {
      title: "Гроссмейстер Эриксоновского Гипноза",
      badge: "Трансовая виртуозность",
      desc: "Вы с легкостью обходите сопротивление и находите ключи к бессознательному клиентов. Ваши сессии экономят силы и дают глубокий результат."
    };
  } else if (score >= 120) {
    return {
      title: "Опытный Практик-Исследователь",
      badge: "Хороший потенциал",
      desc: "Вы интуитивно чувствуете, где поднажать, а где отступить. Но для сложнейших клиентов вам не хватает точных протоколов Милтон-модели."
    };
  } else {
    return {
      title: "Классический Теоретик",
      badge: "Выгорание на сессиях",
      desc: "Вы тратите слишком много сил на логические споры и пробивание «защиты» клиентов. Пора освоить мягкие трансовые методы."
    };
  }
}

export function getQuizResult(answers) {
  const counts = { indirect: 0, trance: 0, resource: 0, somatic: 0 };
  answers.forEach(trait => {
    if (counts[trait] !== undefined) counts[trait]++;
  });
  let maxTrait = 'indirect';
  let maxCount = -1;
  Object.keys(counts).forEach(trait => {
    if (counts[trait] > maxCount) {
      maxCount = counts[trait];
      maxTrait = trait;
    }
  });
  return RESULT_PROFILES[maxTrait] || RESULT_PROFILES.indirect;
}
